use serde::{Deserialize, Serialize};
use ts_rs::TS;

#[cfg(test)]
mod tests;

#[derive(Clone, Debug, Deserialize, TS)]
pub struct CssRect {
    pub left: f64,
    pub top: f64,
    pub width: f64,
    pub height: f64,
}

#[derive(Clone, Debug, Deserialize, TS)]
pub struct ProbeLayout {
    pub session: u32,
    pub revision: u32,
    pub device_pixel_ratio: f64,
    pub rects: Vec<CssRegion>,
}

#[derive(Clone, Debug, Deserialize, TS)]
pub struct CssRegion {
    pub bounds: CssRect,
    pub clip: CssRect,
}

#[derive(Clone, Copy, Debug, Default, Serialize, TS)]
pub struct PhysicalRect {
    pub left: i32,
    pub top: i32,
    pub width: u32,
    pub height: u32,
}

#[derive(Clone, Copy, Debug, Default, Serialize, TS)]
pub struct PhysicalRegion {
    pub bounds: PhysicalRect,
    pub clip: PhysicalRect,
}

#[derive(Clone, Debug, Default, Serialize, TS)]
pub struct ProbeStatus {
    pub layout_session: u32,
    pub generation: u32,
    pub settling: bool,
    pub preview_extents: Option<[[u32; 2]; 2]>,
    pub layout_revision: u32,
    pub rendered_revision: u32,
    pub webview_scale: f64,
    pub browser_scale: f64,
    pub preview_presents: u32,
    pub output_presents: u32,
    pub spout_sends: u32,
    pub source_observations: [u32; 2],
    pub rects: Vec<PhysicalRegion>,
    pub error: Option<String>,
}

#[derive(Clone, Debug, Serialize, TS)]
pub struct BusyCommand {
    pub session: u32,
    pub duration_ms: u32,
}

#[derive(Clone, Debug, Deserialize, TS)]
#[serde(tag = "kind", rename_all = "snake_case")]
pub enum EditorActivity {
    BusyStarted { session: u32 },
    BusyFinished { session: u32, elapsed_ms: f64 },
}

impl ProbeStatus {
    pub fn begin_document(&mut self) -> Result<u32, String> {
        self.layout_session = self.layout_session.checked_add(1).ok_or("layout session exhausted")?;
        self.layout_revision = 0;
        self.rendered_revision = 0;
        self.rects.clear();
        Ok(self.layout_session)
    }

    pub fn apply_layout(&mut self, layout: &ProbeLayout, host_scale: f64) -> Result<(), String> {
        if layout.session != self.layout_session || layout.session == 0 {
            return Err("layout belongs to an expired document".into());
        }
        let physical = layout.physical_rects(host_scale)?;
        if layout.revision > self.layout_revision {
            self.layout_revision = layout.revision;
            self.webview_scale = host_scale;
            self.browser_scale = layout.device_pixel_ratio;
            self.rects = physical;
        }
        Ok(())
    }
}

pub fn bindings() -> String {
    let config = ts_rs::Config::default();
    let declarations = [
        CssRect::decl(&config),
        CssRegion::decl(&config),
        ProbeLayout::decl(&config),
        PhysicalRect::decl(&config),
        PhysicalRegion::decl(&config),
        ProbeStatus::decl(&config),
        BusyCommand::decl(&config),
        EditorActivity::decl(&config),
    ];
    format!(
        "// Generated by generate_probe_bindings; edit the Rust DTOs.\n{}",
        declarations
            .into_iter()
            .map(|decl| format!("export {decl}\n"))
            .collect::<String>()
    )
}

impl ProbeLayout {
    pub fn physical_rects(&self, host_scale: f64) -> Result<Vec<PhysicalRegion>, String> {
        if self.rects.len() > 2
            || !(0.1..=16.0).contains(&host_scale)
            || !(0.1..=16.0).contains(&self.device_pixel_ratio)
        {
            return Err("invalid preview count or scale".into());
        }
        let convert = |rect: &CssRect| -> Result<PhysicalRect, String> {
            if [rect.left, rect.top, rect.width, rect.height]
                .iter()
                .any(|v| !v.is_finite())
                || rect.width < 0.0
                || rect.height < 0.0
                || [rect.left, rect.top, rect.width, rect.height]
                    .iter()
                    .any(|v| v.abs() > 100_000.0)
            {
                return Err("invalid CSS preview bounds".into());
            }
            Ok(PhysicalRect {
                left: (rect.left * host_scale).round() as i32,
                top: (rect.top * host_scale).round() as i32,
                width: (((rect.left + rect.width) * host_scale).round() as i32
                    - (rect.left * host_scale).round() as i32) as u32,
                height: (((rect.top + rect.height) * host_scale).round() as i32
                    - (rect.top * host_scale).round() as i32) as u32,
            })
        };
        self.rects
            .iter()
            .map(|region| {
                Ok(PhysicalRegion {
                    bounds: convert(&region.bounds)?,
                    clip: convert(&region.clip)?,
                })
            })
            .collect()
    }
}
