use crate::{media::protocol::ChannelReference, screens::protocol::ScreenId};
use golden_video::Extent2D;
use serde::{Deserialize, Serialize};
use ts_rs::{Config, TS};

pub const PREVIEW_STATUS_EVENT: &str = "mapgyver-preview-status";
pub const VIDEO_RUNTIME_EVENT: &str = "mapgyver-video-runtime";

#[derive(Clone, Copy, Debug, Serialize, Deserialize, TS)]
#[serde(tag = "kind")]
pub enum VideoRuntimeRequest {
    #[serde(rename = "mapgyverRuntimeStatus")]
    Read,
}

#[derive(Clone, Copy, Debug, PartialEq, Eq, Serialize, Deserialize, TS)]
pub enum VideoRuntimeState {
    Idle,
    Starting,
    Running,
    Recovering,
    Stopped,
    Faulted,
}

#[derive(Clone, Debug, PartialEq, Serialize, Deserialize, TS)]
pub struct VideoResourceUsage {
    /// Renderer-declared tracked allocation charge, not physical VRAM residency.
    pub used_bytes: u64,
    pub limit_bytes: u64,
    pub in_flight: usize,
    pub retiring: usize,
}

#[derive(Clone, Debug, PartialEq, Serialize, Deserialize, TS)]
pub struct VideoRuntimeStatus {
    pub sequence: u64,
    pub state: VideoRuntimeState,
    /// Successful submissions per observed wall-clock interval; not display-present FPS.
    pub submitted_fps: Option<f64>,
    /// Latest successful CPU submit call, excluding asynchronous GPU work.
    pub cpu_submit_ms: Option<f64>,
    pub gpu: Option<String>,
    pub resources: Option<VideoResourceUsage>,
    pub error: Option<String>,
}

#[derive(Clone, Copy, Debug, PartialEq, Eq, Hash, Serialize, Deserialize, TS)]
#[serde(tag = "kind")]
pub enum PreviewSource {
    Channel { reference: ChannelReference },
    Screen { screen: ScreenId },
}

#[derive(Clone, Debug, PartialEq, Serialize, Deserialize, TS)]
pub struct PreviewStatus {
    pub source: PreviewSource,
    pub extent: Option<Extent2D>,
    pub error: Option<String>,
    pub message: Option<String>,
    pub matrix: Option<crate::matrix::protocol::MatrixRenderStatus>,
}

pub fn export_typescript(directory: impl AsRef<std::path::Path>) -> Result<(), Box<dyn std::error::Error>> {
    let directory = directory.as_ref();
    PreviewStatus::export_all(&Config::default().with_out_dir(directory).with_large_int("number"))?;
    VideoRuntimeStatus::export_all(&Config::default().with_out_dir(directory).with_large_int("number"))?;
    VideoRuntimeRequest::export_all(&Config::default().with_out_dir(directory).with_large_int("number"))?;
    std::fs::write(
        directory.join("constants.ts"),
        format!(
            "// Generated by generate_preview_protocol; do not edit.\nexport const PREVIEW_STATUS_EVENT = {PREVIEW_STATUS_EVENT:?};\nexport const VIDEO_RUNTIME_EVENT = {VIDEO_RUNTIME_EVENT:?};\n"
        ),
    )?;
    for entry in std::fs::read_dir(directory)? {
        let path = entry?.path();
        if path.extension().is_some_and(|extension| extension == "ts") {
            let text = std::fs::read_to_string(&path)?;
            let normalized = text.lines().map(str::trim_end).collect::<Vec<_>>().join("\n");
            std::fs::write(path, format!("{normalized}\n"))?;
        }
    }
    Ok(())
}
