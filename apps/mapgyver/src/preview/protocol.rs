use crate::{media::protocol::ChannelReference, screens::protocol::ScreenId};
use golden_video::Extent2D;
use serde::{Deserialize, Serialize};
use ts_rs::{Config, TS};

pub const PREVIEW_STATUS_EVENT: &str = "mapgyver-preview-status";

#[derive(Clone, Copy, Debug, PartialEq, Eq, Hash, Serialize, Deserialize, TS)]
#[serde(tag = "kind")]
pub enum PreviewSource {
    Channel { reference: ChannelReference },
    Screen { screen: ScreenId },
}

#[derive(Clone, Debug, PartialEq, Serialize, Deserialize, TS)]
pub struct PreviewStatus {
    pub source: PreviewSource,
    pub extent: Option<Extent2D>,
    pub error: Option<String>,
    pub message: Option<String>,
}

pub fn export_typescript(directory: impl AsRef<std::path::Path>) -> Result<(), Box<dyn std::error::Error>> {
    let directory = directory.as_ref();
    PreviewStatus::export_all(&Config::default().with_out_dir(directory).with_large_int("number"))?;
    std::fs::write(
        directory.join("constants.ts"),
        format!(
            "// Generated by generate_preview_protocol; do not edit.\nexport const PREVIEW_STATUS_EVENT = {PREVIEW_STATUS_EVENT:?};\n"
        ),
    )?;
    for entry in std::fs::read_dir(directory)? {
        let path = entry?.path();
        if path.extension().is_some_and(|extension| extension == "ts") {
            let text = std::fs::read_to_string(&path)?;
            let normalized = text.lines().map(str::trim_end).collect::<Vec<_>>().join("\n");
            std::fs::write(path, format!("{normalized}\n"))?;
        }
    }
    Ok(())
}
