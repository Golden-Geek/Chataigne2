/*
 * Keyboard module callbacks:
 *   keyboardKeyPressed(key, keyboard)
 *   keyboardKeyReleased(key, keyboard)
 *   keyboardKeyChanged(key, pressed, keyboard)
 *
 * keyboard.heldKeys contains the current supported keys held on the selected device.
 */

function keyboardKeyPressed(key, keyboard) {
  void key;
  void keyboard;
}

function keyboardKeyReleased(key, keyboard) {
  void key;
  void keyboard;
}

function keyboardKeyChanged(key, pressed, keyboard) {
  void key;
  void pressed;
  void keyboard;
}