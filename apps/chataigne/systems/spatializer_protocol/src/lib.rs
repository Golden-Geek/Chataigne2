//! Chataigne-owned Spatializer authoring contracts; no engine or UI implementation.
use golden_model::{NodeId, NodeUuid};
use serde::{Deserialize, Serialize};
use ts_rs::{Config, TS};

pub const SPATIALIZER_NAMESPACE: &str = "chataigne.spatializer";
pub const SPATIALIZER_EDIT_OPERATION: &str = "edit";

#[derive(Clone, Copy, Debug, PartialEq, Eq, Hash, Serialize, Deserialize, TS)]
pub struct SpatializerIdentity {
    pub node: NodeId,
    pub uuid: NodeUuid,
}

#[derive(Clone, Debug, Serialize, Deserialize, TS)]
pub struct SpatializerMove {
    pub endpoint: SpatializerIdentity,
    pub position: [f64; 2],
}

#[derive(Clone, Copy, Debug, Serialize, Deserialize, TS)]
#[serde(rename_all = "camelCase")]
pub enum SpatializerRadius {
    Radius,
    FreezeRadius,
}

#[derive(Clone, Copy, Debug, PartialEq, Eq, Serialize, Deserialize, TS)]
pub enum SpatializerSpace {
    #[serde(rename = "xy")]
    Xy,
    #[serde(rename = "xz")]
    Xz,
}

#[derive(Clone, Debug, Serialize, Deserialize, TS)]
#[serde(tag = "kind", rename_all = "camelCase")]
pub enum SpatializerEdit {
    Move {
        moves: Vec<SpatializerMove>,
    },
    Nudge {
        endpoint: SpatializerIdentity,
        delta: [f64; 2],
    },
    SetRadius {
        endpoint: SpatializerIdentity,
        field: SpatializerRadius,
        value: f64,
    },
    AdjustRadius {
        endpoint: SpatializerIdentity,
        field: SpatializerRadius,
        delta: f64,
    },
    CreateTarget {
        position: [f64; 2],
    },
}

#[derive(Clone, Debug, Serialize, Deserialize, TS)]
pub struct SpatializerEditRequest {
    pub module: SpatializerIdentity,
    pub space: SpatializerSpace,
    pub edit: SpatializerEdit,
}

#[derive(Clone, Debug, Serialize, Deserialize, TS)]
pub struct SpatializerEditResult {
    pub endpoints: Vec<SpatializerIdentity>,
    pub created: Option<SpatializerIdentity>,
}

pub fn export_typescript(directory: impl AsRef<std::path::Path>) -> Result<(), Box<dyn std::error::Error>> {
    let directory = directory.as_ref();
    let config = Config::default().with_out_dir(directory).with_large_int("number");
    SpatializerEditRequest::export_all(&config)?;
    SpatializerEditResult::export_all(&config)?;
    std::fs::write(
        directory.join("constants.ts"),
        format!(
            "// Generated by generate_spatializer_protocol; do not edit.\nexport const SPATIALIZER_NAMESPACE = {SPATIALIZER_NAMESPACE:?};\nexport const SPATIALIZER_EDIT_OPERATION = {SPATIALIZER_EDIT_OPERATION:?};\n"
        ),
    )?;
    Ok(())
}
