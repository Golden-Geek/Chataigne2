//! App-owned state graph editing contracts, shared by native, script and UI callers.

use golden_model::{NodeId, NodeUuid};
use serde::{Deserialize, Serialize};
use ts_rs::{Config, TS};

pub const STATE_GRAPH_NAMESPACE: &str = "chataigne.stateGraph";
pub const STATE_GRAPH_EDIT_OPERATION: &str = "edit";
pub const STATE_GRAPH_INPUT: &str = "transition-input";
pub const STATE_GRAPH_OUTPUT: &str = "transition-output";

#[derive(Clone, Copy, Debug, PartialEq, Eq, Hash, Serialize, Deserialize, TS)]
pub struct StateGraphIdentity {
    pub node: NodeId,
    pub uuid: NodeUuid,
}

#[derive(Clone, Debug, Serialize, Deserialize, TS)]
pub struct StateGraphMove {
    pub state: StateGraphIdentity,
    pub position: [f64; 2],
}

#[derive(Clone, Debug, Serialize, Deserialize, TS)]
pub struct StateGraphSocket {
    pub state: StateGraphIdentity,
    pub socket: String,
}

#[derive(Clone, Debug, Serialize, Deserialize, TS)]
#[serde(tag = "kind", rename_all = "camelCase")]
pub enum StateGraphEdit {
    Move {
        moves: Vec<StateGraphMove>,
    },
    Resize {
        state: StateGraphIdentity,
        size: Option<[f64; 2]>,
    },
    Rename {
        state: StateGraphIdentity,
        label: String,
    },
    Collapse {
        state: StateGraphIdentity,
        collapsed: bool,
    },
    Enable {
        state: StateGraphIdentity,
        enabled: bool,
    },
    Connect {
        from: StateGraphSocket,
        to: StateGraphSocket,
    },
}

#[derive(Clone, Debug, Serialize, Deserialize, TS)]
pub struct StateGraphEditRequest {
    pub manager: StateGraphIdentity,
    pub edit: StateGraphEdit,
}

#[derive(Clone, Debug, Serialize, Deserialize, TS)]
pub struct StateGraphEditResult {
    pub states: Vec<StateGraphIdentity>,
    pub connection: Option<StateGraphIdentity>,
}

pub fn export_typescript(directory: impl AsRef<std::path::Path>) -> Result<(), Box<dyn std::error::Error>> {
    let directory = directory.as_ref();
    let config = Config::default().with_out_dir(directory).with_large_int("number");
    StateGraphEditRequest::export_all(&config)?;
    StateGraphEditResult::export_all(&config)?;
    std::fs::write(
        directory.join("state-graph-constants.ts"),
        format!(
            "// Generated by generate_state_machine_protocol; do not edit.\n\
         export const STATE_GRAPH_NAMESPACE = {STATE_GRAPH_NAMESPACE:?};\n\
         export const STATE_GRAPH_EDIT_OPERATION = {STATE_GRAPH_EDIT_OPERATION:?};\n\
         export const STATE_GRAPH_INPUT = {STATE_GRAPH_INPUT:?};\n\
         export const STATE_GRAPH_OUTPUT = {STATE_GRAPH_OUTPUT:?};\n"
        ),
    )?;
    Ok(())
}
