//! App-owned Formula operation DTOs; complete authored documents stay opaque to the UI.

use golden_engine::{
    engine::ProjectFile,
    node::{NodeId, NodeUuid},
};
use serde::{Deserialize, Serialize};
use ts_rs::{Config, TS};

pub const FORMULA_OPERATION_NAMESPACE: &str = "chataigne.alchemist";
pub const FORMULA_COPY_OPERATION: &str = "copyFragment";
pub const FORMULA_PASTE_OPERATION: &str = "pasteFragment";
pub const FORMULA_CONNECT_OPERATION: &str = "connect";
pub const FORMULA_GRAPH_EDIT_OPERATION: &str = "editGraph";
pub const FORMULA_FRAGMENT_VERSION: u32 = 1;

#[derive(Clone, Debug, Serialize, Deserialize, TS)]
pub struct FormulaOwnerDto {
    pub node: NodeId,
    pub uuid: NodeUuid,
}

#[derive(Clone, Debug, Serialize, Deserialize, TS)]
pub struct FormulaCopyRequest {
    pub formula: FormulaOwnerDto,
    pub nodes: Vec<NodeId>,
}

#[derive(Clone, Debug, Serialize, Deserialize, TS)]
pub struct FormulaFragmentItem {
    /// Complete dense persistence capsule. Only the backend interprets its schema.
    #[ts(as = "serde_json::Value")]
    pub document: ProjectFile,
    /// Authored placement captured by the backend; paste accepts an explicit offset hint.
    pub position: Option<[f64; 2]>,
}

#[derive(Clone, Debug, Serialize, Deserialize, TS)]
pub struct FormulaFragment {
    pub version: u32,
    pub source_formula_uuid: NodeUuid,
    pub items: Vec<FormulaFragmentItem>,
}

#[derive(Clone, Debug, Serialize, Deserialize, TS)]
pub struct FormulaPasteRequest {
    pub formula: FormulaOwnerDto,
    pub fragment: FormulaFragment,
    pub offset: Option<[f64; 2]>,
}

#[derive(Clone, Debug, Serialize, Deserialize, TS)]
pub struct FormulaImportedIdentity {
    pub source_uuid: NodeUuid,
    pub uuid: NodeUuid,
    pub node: NodeId,
}

#[derive(Clone, Debug, Serialize, Deserialize, TS)]
pub struct FormulaPasteResult {
    pub selected_nodes: Vec<NodeId>,
    pub identities: Vec<FormulaImportedIdentity>,
}

#[derive(Clone, Debug, Serialize, Deserialize, TS)]
pub struct FormulaSocketDto {
    pub node: NodeId,
    pub uuid: NodeUuid,
    pub socket: String,
}

#[derive(Clone, Debug, Serialize, Deserialize, TS)]
pub struct FormulaConnectRequest {
    pub formula: FormulaOwnerDto,
    pub from: FormulaSocketDto,
    pub to: FormulaSocketDto,
}

#[derive(Clone, Debug, Serialize, Deserialize, TS)]
pub struct FormulaConnectResult {
    pub connection: FormulaOwnerDto,
    pub replaced: Vec<FormulaOwnerDto>,
}

#[derive(Clone, Debug, Serialize, Deserialize, TS)]
pub struct FormulaGraphMove {
    pub anode: FormulaOwnerDto,
    pub position: [f64; 2],
}

#[derive(Clone, Debug, Serialize, Deserialize, TS)]
#[serde(tag = "kind", rename_all = "camelCase")]
pub enum FormulaGraphEdit {
    Delete {
        nodes: Vec<FormulaOwnerDto>,
    },
    Move {
        moves: Vec<FormulaGraphMove>,
    },
    Resize {
        anode: FormulaOwnerDto,
        size: Option<[f64; 2]>,
    },
    Rename {
        anode: FormulaOwnerDto,
        label: String,
    },
    Collapse {
        anode: FormulaOwnerDto,
        collapsed: bool,
    },
    Enable {
        anode: FormulaOwnerDto,
        enabled: bool,
    },
}

#[derive(Clone, Debug, Serialize, Deserialize, TS)]
pub struct FormulaGraphEditRequest {
    pub formula: FormulaOwnerDto,
    pub edit: FormulaGraphEdit,
}

#[derive(Clone, Debug, Serialize, Deserialize, TS)]
pub struct FormulaGraphEditResult {
    pub nodes: Vec<FormulaOwnerDto>,
}

pub fn export_typescript(directory: impl AsRef<std::path::Path>) -> Result<(), Box<dyn std::error::Error>> {
    let directory = directory.as_ref();
    let config = Config::default().with_out_dir(directory).with_large_int("number");
    FormulaCopyRequest::export_all(&config)?;
    FormulaPasteRequest::export_all(&config)?;
    FormulaPasteResult::export_all(&config)?;
    FormulaConnectRequest::export_all(&config)?;
    FormulaConnectResult::export_all(&config)?;
    FormulaGraphEditRequest::export_all(&config)?;
    FormulaGraphEditResult::export_all(&config)?;
    std::fs::write(
        directory.join("constants.ts"),
        format!(
            "// Generated by generate_alchemist_authoring; do not edit.\n\
             export const FORMULA_OPERATION_NAMESPACE = {FORMULA_OPERATION_NAMESPACE:?};\n\
             export const FORMULA_COPY_OPERATION = {FORMULA_COPY_OPERATION:?};\n\
             export const FORMULA_PASTE_OPERATION = {FORMULA_PASTE_OPERATION:?};\n\
             export const FORMULA_CONNECT_OPERATION = {FORMULA_CONNECT_OPERATION:?};\n\
             export const FORMULA_GRAPH_EDIT_OPERATION = {FORMULA_GRAPH_EDIT_OPERATION:?};\n\
             export const FORMULA_FRAGMENT_VERSION = {FORMULA_FRAGMENT_VERSION};\n"
        ),
    )?;
    Ok(())
}
