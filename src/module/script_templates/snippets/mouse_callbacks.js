/*
 * Mouse module callbacks:
 *   mouseMoved(position, delta, mouse)
 *   mouseButtonPressed(button, mouse)
 *   mouseButtonReleased(button, mouse)
 *   mouseButtonChanged(button, pressed, mouse)
 *
 * Mouse input tracks pointer movement plus left, middle, and right button state.
 */

function mouseMoved(position, delta, mouse) {
  void position;
  void delta;
  void mouse;
}

function mouseButtonPressed(button, mouse) {
  void button;
  void mouse;
}

function mouseButtonReleased(button, mouse) {
  void button;
  void mouse;
}

function mouseButtonChanged(button, pressed, mouse) {
  void button;
  void pressed;
  void mouse;
}